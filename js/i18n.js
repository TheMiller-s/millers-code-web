document.addEventListener('DOMContentLoaded', () => {
  const userLang = navigator.language || navigator.userLanguage;
  let currentLang = localStorage.getItem('site_lang');
  
  if (!currentLang) {
    if (userLang.startsWith('en')) currentLang = 'en';
    else if (userLang.startsWith('de')) currentLang = 'de';
    else if (userLang.startsWith('fr')) currentLang = 'fr';
    else if (userLang.startsWith('pt')) currentLang = 'pt';
    else currentLang = 'es';
  }

  const applyTranslations = (lang) => {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (translations[lang] && translations[lang][key]) {
        el.innerHTML = translations[lang][key];
      }
    });

    document.querySelectorAll('[data-wa]').forEach(el => {
      const key = el.getAttribute('data-wa');
      if (translations[lang] && translations[lang][key] && el.tagName === 'A') {
        try {
          const url = new URL(el.href);
          url.searchParams.set('text', translations[lang][key]);
          el.href = url.toString();
        } catch (e) {
          console.error("Error updating WhatsApp link:", e);
        }
      }
    });

    const langSelectors = document.querySelectorAll('.lang-selector button');
    langSelectors.forEach(btn => {
      btn.style.opacity = btn.getAttribute('data-lang') === lang ? '1' : '0.5';
    });
  };

  applyTranslations(currentLang);

  window.changeLanguage = (lang) => {
    localStorage.setItem('site_lang', lang);
    applyTranslations(lang);
  };
});
